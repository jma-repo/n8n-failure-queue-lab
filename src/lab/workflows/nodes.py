"""Helpers that emit n8n workflow JSON. Node ids come from names, so rebuilding gives a clean git diff."""

from __future__ import annotations

import uuid
from typing import Any

from lab.paths import N8N_DIR

NS = uuid.UUID("6f0a1c52-3a7e-4c52-9d60-5a1d5f0f2b11")
CODE_DIR = N8N_DIR / "code"
HEADER = "// Generated by scripts/build_workflows.py from n8n/code/. Edit those files, not this node.\n"
API_KEY = {"name": "X-API-Key", "value": "={{ $env.LAB_API_TOKEN }}"}
SMTP = {"smtp": {"id": "labSmtp01", "name": "Mailpit SMTP"}}


class Workflow:
    def __init__(self, wid: str, name: str, *, error_workflow: str | None = None) -> None:
        self.wid, self.name, self.error_workflow = wid, name, error_workflow
        self.nodes: list[dict[str, Any]] = []
        self.connections: dict[str, dict[str, list[list[dict[str, Any]]]]] = {}

    def add(self, name: str, kind: str, version: float, params: dict[str, Any], at: tuple[float, float], **extra: Any) -> str:
        node = {
            "parameters": params,
            "id": str(uuid.uuid5(NS, f"{self.wid}/{name}")),
            "name": name,
            "type": f"n8n-nodes-base.{kind}",
            "typeVersion": version,
            "position": [int(240 * at[0]), int(200 * at[1])],
        }
        self.nodes.append({**node, **extra})
        return name

    def link(self, src: str, dst: str, output: int = 0) -> None:
        outputs = self.connections.setdefault(src, {"main": []})["main"]
        while len(outputs) <= output:
            outputs.append([])
        outputs[output].append({"node": dst, "type": "main", "index": 0})

    def chain(self, *names: str) -> None:
        for src, dst in zip(names, names[1:], strict=False):
            self.link(src, dst)

    def to_json(self) -> dict[str, Any]:
        settings = {"executionOrder": "v1", "timezone": "America/Edmonton"}
        if self.error_workflow:
            settings["errorWorkflow"] = self.error_workflow
        return {
            "name": self.name,
            "nodes": self.nodes,
            "connections": self.connections,
            "settings": settings,
            "id": self.wid,
            "pinData": {},
            "tags": [],
            "meta": {"templateCredsSetupCompleted": True},
        }


def js(entry: str, **consts: str) -> str:
    """Source of a Code node: the shared library when the entry asks for it, then the entry itself."""
    body = (CODE_DIR / f"{entry}.entry.js").read_text(encoding="utf-8")
    uses = body.splitlines()[0].removeprefix("// uses:").strip()
    for key, value in consts.items():
        body = body.replace(f"__{key}__", value)
    library = (CODE_DIR / "validate.js").read_text(encoding="utf-8") + "\n" if uses == "validate" else ""
    return HEADER + library + body


def code(w: Workflow, name: str, entry: str, at: tuple[float, float], **consts: str) -> str:
    params = {"mode": "runOnceForAllItems", "language": "javaScript", "jsCode": js(entry, **consts)}
    return w.add(name, "code", 2, params, at)


def schedule(w: Workflow, name: str, minutes: int, at: tuple[float, float]) -> str:
    rule = {"interval": [{"field": "minutes", "minutesInterval": minutes}]}
    return w.add(name, "scheduleTrigger", 1.4, {"rule": rule}, at)


def webhook(w: Workflow, name: str, path: str, at: tuple[float, float]) -> str:
    params = {"httpMethod": "POST", "path": path, "responseMode": "onReceived", "options": {}}
    return w.add(name, "webhook", 2.2, params, at, webhookId=str(uuid.uuid5(NS, f"{w.wid}/hook/{path}")))


def http_api(
    w: Workflow, name: str, method: str, path: str, at: tuple[float, float], body: str | None = None, *, fail_open: bool = False
) -> str:
    """A call to the queue API: key header, JSON body from an expression, 15 s timeout."""
    params: dict[str, Any] = {
        "method": method,
        "url": "={{ $env.LAB_QUEUE_URL }}" + path,
        "sendHeaders": True,
        "headerParameters": {"parameters": [API_KEY]},
        "options": {"timeout": 15000},
    }
    if body:
        params.update(sendBody=True, contentType="json", specifyBody="json", jsonBody=body)
    extra = {"onError": "continueRegularOutput"} if fail_open else {}
    return w.add(name, "httpRequest", 4.5, params, at, **extra)


def http_source(w: Workflow, name: str, at: tuple[float, float]) -> str:
    """The source fetch. Errors from the HTTP node (timeouts, resets) are retried 3x here; the answer is never thrown on."""
    params = {
        "method": "GET",
        "url": "={{ $json.source_url }}",
        "options": {"timeout": 10000, "response": {"response": {"fullResponse": True, "neverError": True, "responseFormat": "text"}}},
    }
    return w.add(name, "httpRequest", 4.5, params, at, retryOnFail=True, maxTries=3, waitBetweenTries=2000, onError="continueRegularOutput")


def cond(w: Workflow, name: str, left: str, kind: str, operation: str, right: Any, at: tuple[float, float]) -> str:
    leaf = {"id": str(uuid.uuid5(NS, f"{w.wid}/{name}/c")), "leftValue": left, "rightValue": right, "operator": {"type": kind, "operation": operation}}
    if kind == "boolean":
        leaf["operator"]["singleValue"] = True
        leaf["rightValue"] = ""
    options = {"caseSensitive": True, "leftValue": "", "typeValidation": "strict", "version": 2}
    return w.add(name, "if", 2.2, {"conditions": {"options": options, "conditions": [leaf], "combinator": "and"}, "options": {}}, at)


def email(w: Workflow, name: str, at: tuple[float, float]) -> str:
    params = {
        "fromEmail": "lab-alerts@lab.test",
        "toEmail": "={{ $env.LAB_ALERT_TO }}",
        "subject": "={{ $('Split alerts').item.json.subject }}",
        "emailFormat": "text",
        "text": "={{ $('Split alerts').item.json.body }}",
        "options": {"appendAttribution": False},
    }
    return w.add(name, "emailSend", 2.1, params, at, credentials=SMTP)


def note(w: Workflow, text: str, at: tuple[float, float], width: int, height: int, color: int = 7) -> str:
    return w.add(f"Note {len(w.nodes)}", "stickyNote", 1, {"content": text, "height": height, "width": width, "color": color}, at)


def alert_tail(w: Workflow, prev: str, source: str, at: tuple[float, float]) -> None:
    """Split alerts -> cool-down check in the queue API -> email, shared by every workflow."""
    x, y = at
    split = code(w, "Split alerts", "split_alerts", (x, y), SOURCE=source)
    # fail open: when the queue API cannot answer, send the alert anyway rather than lose it
    throttle = http_api(w, "Throttle alert", "POST", "/v1/alerts", (x + 1, y), body="={{ JSON.stringify($json) }}", fail_open=True)
    gate = cond(w, "Send now?", "={{ $json.send !== false }}", "boolean", "true", True, (x + 2, y))
    mail = email(w, "Send alert email", (x + 3, y))
    w.chain(prev, split, throttle, gate)
    w.link(gate, mail, 0)
